#!/usr/bin/env python3
"""build.py — assembles the CORE that the Worker serves, from this repository alone, as worker/src/core_bundle.py.

The served CORE holds the installed release copy (extensions/), the pin and the lock (.commons/), and the users-free
access and the register of served/. Nothing is generated or changed: every file is packed as it is, into one zip
carried by a Python module, because a Python Worker's bundle carries its modules but not every other file, and no
folder whose name begins with a dot. The Worker unpacks it at start (mcp_http.py). The module is build output and
never committed.

Usage:  python -B deploy/build.py
"""
import base64
import hashlib
import io
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "worker", "src", "core_bundle.py")
COPY = [("extensions", "extensions"), (".commons/commons.yml", ".commons/commons.yml"), (".commons/lock.yml", ".commons/lock.yml"),
        ("served/.commons/access.yml", ".commons/access.yml"), ("served/graph/sources.yml", "graph/sources.yml")]


def files():
    for src, dst in COPY:
        s = os.path.join(ROOT, src)
        if os.path.isfile(s):
            yield s, dst
            continue
        for d, dirs, fs in os.walk(s):
            dirs[:] = sorted(x for x in dirs if x != "__pycache__")
            for f in sorted(fs):
                if not f.endswith(".pyc"):
                    p = os.path.join(d, f)
                    yield p, dst + "/" + os.path.relpath(p, s).replace(os.sep, "/")


def main():
    buf, n = io.BytesIO(), 0
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p, name in files():
            z.writestr(zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0)), open(p, "rb").read(), zipfile.ZIP_DEFLATED)
            n += 1
    data = buf.getvalue()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# generated by deploy/build.py: the served CORE as one zip; never edited, never committed\n")
        f.write(f"DIGEST = 'sha256:{hashlib.sha256(data).hexdigest()}'\n")
        f.write(f"ZIP = '{base64.b64encode(data).decode()}'\n")
    print(f"served CORE: {n} files, {len(data)} bytes zipped, in {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
