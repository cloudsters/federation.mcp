#!/usr/bin/env python3
"""answer_graph.py — from a context and a problem to a few candidates of the CORE's graph (graph.md R12-R14, R24). Read-only.

The reference answer path of GRAPH, which carries on what `lookup_patterns.py` did for the installed extract alone
(core.md R32). Four rules carry it:

- **Ownership.** Every file belongs to exactly one source of the register: a source nested in another's folder owns
  its own files, for reading and for its digest alike (R2).
- **The cut is what was read.** A source is read from git at HEAD where its files are clean, and otherwise from its
  working files at the time they were read; an installed extract is read only where its index has the lock's digest (R12).
- **Projection before traversal.** The whole graph is read once; a caller is then served only nodes of sources it may
  see, stated edges whose both ends it may see, and computed edges whose every input it may see today, as the register
  holds them, with no input withdrawn (R13, R24). What was withheld shows as a flag, never as an id or a count.
- **Readers per kind.** `registry`, `knowledge`, `operations`, `views`, `specs`, `patterns` and `bill` are read; a
  permitted source of another kind is reported as not read, with its reason, never silently dropped.
- **Bills are single-level.** A CORE's bill is generated by CORE and read as a source; `resolve` walks it down, level
  by level, and `where_used` reads it backwards over the COREs a caller may read; neither is stored (R26, R27).

It matches the words of the question against every visible node, then widens the best hits along stated edges, the
family join first (R14), and along the computed edges of released runs, the commons' own and the foreign run an
installed extract carries (R11). Each candidate names its file; the agent opens only the file it uses.

Usage:  answer_graph.py CORE "context and problem" [--k 3] [--classes public,member] [--json]
"""
