def stem(w):
    for end in ("ing", "ed", "es", "s"):
        if w.endswith(end) and len(w) - len(end) >= 4:
            return w[: -len(end)]
    return w


def words(text):
    return {stem(w) for w in WORD.findall(str(text).lower()) if w not in STOP and len(w) > 2}


def norm(b):
    return b.replace(b"\r\n", b"\n")


def sha(b):
    return hashlib.sha256(norm(b)).hexdigest()


def filehash(path):
    return sha(open(path, "rb").read())


def restrictions(*classes):
    """the restrictions of some inputs: every class other than `public`, as a set; a reader must be allowed each"""
    out = set()
    for c in classes:
        out |= set(c) if isinstance(c, (list, set, tuple)) else ({c} if c else set())
    return out - {"public"}


def as_class(rs):
    """the form an edge or proposal records: `public`, one class, or the sorted list of its restrictions"""
    rs = sorted(rs)
    return "public" if not rs else (rs[0] if len(rs) == 1 else rs)


def may_see(rs, classes):
    return classes is None or set(rs) <= set(classes) | {"public"}


def git(core, *args):
    try:
        out = subprocess.run(["git", "-C", core, *args], capture_output=True)
        return out.stdout if out.returncode == 0 else None
    except OSError:
        return None


class Tree:
    """the CORE's working files"""

    def __init__(self, core):
        self.core = core

    def files(self, ref):
        base = os.path.join(self.core, ref)
        if os.path.isfile(base):
            return [key_of(ref)]
        out = []
        for d, _, fs in os.walk(base):
            out += [os.path.relpath(os.path.join(d, f), self.core).replace(os.sep, "/") for f in fs]
        return sorted(out)

    def exists(self, ref):
        return os.path.exists(os.path.join(self.core, ref))

    def read(self, rel):
        return open(os.path.join(self.core, rel), "rb").read()


class GitTree(Tree):
    """the CORE's files as git held them at a revision"""

    def __init__(self, core, rev):
        super().__init__(core)
        self.rev = rev
        self.pre = (git(core, "rev-parse", "--show-prefix") or b"").decode().strip()
        listing = git(core, "ls-tree", "-r", "--full-name", "--name-only", rev, "--", ".")
        self.all = None if listing is None else sorted(p[len(self.pre):] for p in listing.decode().splitlines() if p.startswith(self.pre))

    def files(self, ref):
        r = key_of(ref)
        return [p for p in self.all or [] if p == r or p.startswith(r + "/")]

    def exists(self, ref):
        return bool(self.files(ref))

    def read(self, rel):
        return git(self.core, "show", f"{self.rev}:{self.pre}{rel}")


def at(core, rev):
    """a tree at a revision, or None where git cannot read it"""
    if not rev or not git(core, "rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}"):
        return None
    t = GitTree(core, rev)
    return t if t.all is not None else None


def key_of(ref):
    return os.path.normpath(ref).replace(os.sep, "/").rstrip("/")


def owned(register, entry, files):
    """the files of a source: those under its `ref` and under no other source nested inside it (R2)"""
    mine = key_of(entry["ref"])
    inner = [key_of(o["ref"]) for o in register if o is not entry and key_of(o["ref"]).startswith(mine + "/")]
    return [f for f in files if not any(f == i or f.startswith(i + "/") for i in inner)]


def digest(snapshot, register, entry):
    h = hashlib.sha256()
    for f in owned(register, entry, snapshot.files(entry["ref"])):
        h.update(f"{f}\0{sha(snapshot.read(f))}\n".encode())
    return "sha256:" + h.hexdigest()


def overlaps(register):
    """pairs of entries that claim the same files"""
    seen, out = {}, []
    for e in register:
        k = key_of(e["ref"])
        if k in seen:
            out.append((seen[k], e["id"]))
        seen.setdefault(k, e["id"])
    return out


def yml(path):
    return yaml.safe_load(open(path, encoding="utf-8")) or {}


def yaml_bytes(b):
    return (yaml.safe_load(b.decode("utf-8")) or {}) if b else {}


def lock_of(core):
    p = os.path.join(core, ".commons", "lock.yml")
    return yml(p) if os.path.isfile(p) else {}


def lock_entry(lock, ref):
    return next((p for p in lock.get("patterns") or [] if f"patterns/{p.get('path')}" == key_of(ref)), None)


def pin_of(snap, lock, ref):
    """an installed extract's pin (core R29): its lock entry, `{path, origin, record}`, and its record `release.yml`
    beside the index, read only where it has the digest the lock records and the extract's files the part digest the
    record names, the one digest of a copy (library R3, R9), so that no body changed after install is served as the
    release; the record gives the index's digest and the released run. Returns (pin, why not)"""
    entry, rp = lock_entry(lock, ref), f"{key_of(ref)}/release.yml"
    if entry is None or not snap.exists(rp):
        return None, "the lock records no extract here, or its record is missing"
    b = snap.read(rp)
    if f"sha256:{sha(b)}" != entry.get("record"):
        return None, "its record is not the one the lock pins"
    rec = yaml_bytes(b) or {}
    import check_library   # here, not above: the one digest of a copy is LIBRARY's
    part = (rec.get("parts") or {}).get(check_library.INSTALLED["extract"]) if isinstance(rec.get("parts"), dict) else None
    base = key_of(ref)
    held = [(f[len(base) + 1:], lambda f=f: snap.read(f)) for f in snap.files(base)]
    if not isinstance(part, dict) or part.get("digest") != check_library.digest_of(held):
        return None, "its files are not those its pinned record's part digest names"
    return {**entry, "digest": rec.get("digest"), "graph_run": rec.get("graph_run")}, None


class Graph:
    """everything read from the register: nodes, edges, the cut, and the sources not read"""

    def __init__(self, core, register, lock):
        self.core, self.register, self.lock = core, register, lock
        self.nodes, self.edges, self.cut, self.unread, self.bills = {}, [], [], [], {}
        p = os.path.join(core, ".commons", "commons.yml")
        self.core_id = str((yml(p) if os.path.isfile(p) else {}).get("id") or os.path.basename(os.path.normpath(core)))
        self.by_id = {e["id"]: e for e in register}

    def node(self, nid, source, file=None, text="", content=None):
        self.nodes.setdefault(nid, {"source": source, "file": file, "text": text, "content": content})

    def edge(self, frm, kind, to, by, source, **extra):
        self.edges.append({"from": frm, "kind": kind, "to": to, "by": by, "source": source, **extra})

    def cls(self, source):
        e = self.by_id.get(source)
        return e["class"] if e else None


def reader(kind):
    def wrap(f):
        READERS[kind] = f
        return f
    return wrap


def ymls(snap, g, e):
    for f in owned(g.register, e, snap.files(e["ref"])):
        if f.endswith((".yml", ".yaml")):
            try:
                x = yaml_bytes(snap.read(f))
            except yaml.YAMLError:
                continue
            if isinstance(x, dict):
                yield f, x


@reader("registry")
def read_registry(snap, e, g):
    for f, x in ymls(snap, g, e):
        k, s = x.get("kind"), x.get("slug")
        if not k or not s:
            continue
        nid = f"{k}:{s}"
        g.node(nid, e["id"], f, " ".join(str(v) for v in (str(s).replace("-", " "), x.get("title"), x.get("stated_as")) if v), x)
        for field, target in FIELDS.get(k, []):
            for t in as_list(x.get(field)):
                g.edge(nid, f"{nid}#{field}:{t}", t if ":" in str(t) else f"{target}:{t}", "stated", e["id"])
        if k == "value-stream":
            if x.get("family"):
                g.edge(nid, f"{nid}#family:{x['family']}", f"family:{x['family']}", "stated", e["id"])
            for st in x.get("steps") or []:
                sid = f"step:{s}/{st.get('slug')}"
                g.node(sid, e["id"], f, f"{str(st.get('slug', '')).replace('-', ' ')} {st.get('title') or ''}", st)
                g.edge(sid, "part_of", nid, "stated", e["id"])
                for field, target in (("capabilities", "capability"), ("entities", "entity")):
                    for t in st.get(field) or []:
                        g.edge(sid, f"value-stream:{s}/{st.get('slug')}#{field}:{t}", f"{target}:{t}", "stated", e["id"])


@reader("knowledge")
def read_knowledge(snap, e, g):
    for f, x in ymls(snap, g, e):
        for s in (x.get("sources") or []) if f.endswith("sources.yml") else []:
            g.node(f"source:{s['id']}", e["id"], f, s.get("title") or "", s)
        for c in (x.get("claims") or []) if f.endswith("claims.yml") else []:
            cid = f"claim:{c['id']}"
            g.node(cid, e["id"], f, c.get("statement") or "", c)
            for s in c.get("sources") or []:
                g.edge(cid, "sources", f"source:{s}", "stated", e["id"])
            for i in c.get("inputs") or []:          # a derived claim's inputs (core-knowledge)
                g.edge(cid, "inputs", f"claim:{i}", "stated", e["id"])
            for a in c.get("about") or []:
                g.edge(cid, "about", a if ":" in a else f"*:{a}", "stated", e["id"])


@reader("operations")
def read_operations(snap, e, g):
    for f, x in ymls(snap, g, e):
        if x.get("id") and "watches" in x:
            lid = f"loop:{x['id']}"
            g.node(lid, e["id"], f, f"{x.get('title') or ''} {str(x['id']).replace('-', ' ')}", x)
            for t in as_list(x.get("watches")):
                g.edge(lid, "watches", t, "stated", e["id"])


@reader("views")
def read_views(snap, e, g):
    """a view as `view:<name>`, its folder (core-views R5), and a blueprint section as `section:<id>` (core-views R1),
    so that a curriculum's next path is a node any grant may be given (learn R2)"""
    for f, x in ymls(snap, g, e):
        if f.endswith("/view.yml"):
            vid = "view:" + f.rsplit("/", 2)[-2]
            g.node(vid, e["id"], f, " ".join(str(x.get(k) or "") for k in ("name", "kind", "audience", "promise")), x)
            for s in as_list(x.get("sections")):
                g.edge(vid, "sections", f"section:{s}", "stated", e["id"])
            for a in as_list(x.get("after")):
                g.edge(vid, "after", f"view:{a}", "stated", e["id"])
        for s in x.get("sections") or [] if f.endswith("/blueprint.yml") else []:
            if not isinstance(s, dict) or not s.get("id"):
                continue
            sid, b = f"section:{s['id']}", s.get("binds") if isinstance(s.get("binds"), dict) else {}
            g.node(sid, e["id"], f, " ".join([str(s["id"]).replace(".", " ")] + [str(v) for v in (s.get("labels") or {}).values()]), s)
            if b.get("kind") and b.get("slug"):
                g.edge(sid, "binds", f"{b['kind']}:{b['slug']}", "stated", e["id"])


@reader("bill")
def read_bill(snap, e, g):
    """the CORE as `core:<id>`, each part of its bill by the identity CORE gives it (core R37), and each release a part
    belongs to as `<library>/<id>@<version>` (library R3): `uses` from the CORE to a part with its usage, `part_of` from
    a part to its release, `made_in` from a release to the CORE and commit its record names (R26)"""
    b = g.bills.get(e["id"]) or {}
    cid = f"core:{g.core_id}"
    g.node(cid, e["id"], key_of(e["ref"]), f"{g.core_id} bill of materials", {k: v for k, v in b.items() if k != "lines"})
    held = records(g.core, g.lock)
    for x in b.get("lines") or []:
        pid = str(x["part"])
        g.node(pid, e["id"], key_of(e["ref"]), f"{pid.replace('/', ' ').replace('@', ' ').replace('#', ' ')} {x['usage']}", x)
        g.edge(cid, "uses", pid, "stated", e["id"], usage=x["usage"])
        rel = release_of(x)
        if rel and rel in held:
            f, rec = held[rel]
            g.node(rel, e["id"], f, rel.replace("/", " ").replace("@", " "), {k: rec.get(k) for k in ("kind", "version", "made_in", "licence", "parts")})
            g.edge(pid, "part_of", rel, "stated", e["id"])
            if rec.get("made_in"):
                g.edge(rel, "made_in", str(rec["made_in"]), "stated", e["id"])


def release_of(line):
    """the release a line's part belongs to, `<library>/<id>@<version>`, where the line names a record (core R37)"""
    return str(line["part"]).split("#", 1)[0] if line.get("record") and "#" in str(line["part"]) else None


def records(core, lock):
    """the release records the CORE holds for what its lock installs or serves: release -> (file, record), each read
    only where it has the digest the lock records (core R29; library R3)"""
    out = {}
    held = [("extensions/" + str(x.get("id")), x.get("record")) for x in lock.get("extensions") or [] if isinstance(x, dict)]
    held += [("patterns/" + str(x.get("path")), x.get("record")) for x in lock.get("patterns") or [] if isinstance(x, dict)]
    for d, digest_ in held:
        f = os.path.join(core, d, "release.yml")
        if not os.path.isfile(f) or f"sha256:{filehash(f)}" != digest_:
            continue
        rec = yml(f)
        rid = rec.get("extension") if rec.get("kind") == "extension" else "patterns"
        out[f"{rec.get('library')}/{rid}@{rec.get('version')}"] = (f"{d}/release.yml", rec)
    return out


def bill_of(core):
    """the CORE's bill as CORE generates it (core R37), or (None, why) where none is generated"""
    import check_core   # here, not above: the bill is CORE's
    rep = check_core.check(core, offline=True)
    b = getattr(rep, "bill", None)
    if not b:
        return None, "no bill is generated: a finding on what it lists withholds it (core R37)"
    return b, None


@reader("specs")
def read_specs(snap, e, g):
    for f in owned(g.register, e, snap.files(e["ref"])):
        if f.endswith(".md") and f.count("/") == key_of(e["ref"]).count("/") + 1:
            spec = os.path.splitext(os.path.basename(f))[0]
            for line in snap.read(f).decode("utf-8", "replace").splitlines():
                m = re.match(r"^\| (R\d+) \| (MUST|SHOULD) \| (.+?) \|", line)
                if m:
                    g.node(f"{spec}#{m[1]}", e["id"], f, m[3], line)


def front(b):
    t = b.decode("utf-8", "replace") if b else ""
    if not t.startswith("---"):
        return None
    try:
        fm = yaml.safe_load(t.split("---", 2)[1])
    except yaml.YAMLError:
        return None
    return fm if isinstance(fm, dict) else None


@reader("patterns")
def read_patterns(snap, e, g):
    base = key_of(e["ref"])
    if e.get("pin") == "lock":
        entry = pin_of(snap, g.lock, e["ref"])[0] or {}
        for line in snap.read(f"{base}/index.jsonl").decode("utf-8").splitlines():
            x = json.loads(line) if line.strip() else {}
            if x.get("kind") != "pattern":
                continue
            c = x.get("context") or {}
            pf = f"{base}/{x.get('file') or ''}"
            g.node(x["id"], e["id"], pf,
                   " ".join([x.get("title") or "", x.get("tension") or "", x.get("summary") or "", c.get("sector") or ""]
                            + list(c.get("labels") or [])),
                   snap.read(pf).decode("utf-8", "replace") if x.get("file") and snap.exists(pf) else x)
            for fam in c.get("families") or []:
                g.edge(x["id"], "context.families", "family:" + fam.split(":", 1)[-1], "stated", e["id"])
            for l in x.get("links") or []:
                if l.get("by") == "computed":        # the edges of the federation's released run (R11)
                    g.edge(x["id"], l.get("kind") or "unclassified", l.get("to"), "computed", e["id"],
                           run=entry.get("graph_run"), method=l.get("method"), restrict=restrictions(e["class"]))
                else:
                    g.edge(x["id"], l.get("kind") or "unclassified", l.get("to"), "stated", e["id"])
        return
    cid = yaml_bytes(snap.read(".commons/commons.yml")).get("id", "core") if snap.exists(".commons/commons.yml") else "core"
    for f in owned(g.register, e, snap.files(e["ref"])):
        if not f.endswith(".md") or f.count("/") != base.count("/") + 1:
            continue
        fm = front(snap.read(f))
        if not fm or not fm.get("id"):
            continue
        nid = f"{cid}/{fm['id']}"
        g.node(nid, e["id"], f, " ".join(str(fm.get(k) or "") for k in ("title", "summary")), snap.read(f).decode("utf-8", "replace"))
        a = fm.get("adopted_from")
        if isinstance(a, dict) and a.get("id"):
            g.edge(nid, "adopted_from", a["id"], "stated", e["id"])


def register_of(core):
    p = os.path.join(core, "graph", "sources.yml")
    doc = yml(p) if os.path.isfile(p) else {}
    return [e for e in doc.get("sources") or [] if isinstance(e, dict) and {"id", "kind", "ref", "class"} <= set(e)]


def dirty(core, register, e):
    """whether a source's working files differ from HEAD, or git cannot tell"""
    out = git(core, "status", "--porcelain", "--untracked-files=all", "--", e["ref"])
    if out is None:
        return True
    pre = (git(core, "rev-parse", "--show-prefix") or b"").decode().strip()
    paths = [l[3:].strip().strip('"') for l in out.decode().splitlines() if l.strip()]
    return bool(owned(register, e, [p[len(pre):] if p.startswith(pre) else p for p in paths]))


def read(core, snapshots=None, only=None):
    """the whole graph of a CORE. `snapshots` maps a source to the tree it is read from (default: the working files);
    `only` limits reading to some sources, as a run's cut does"""
    register, lock = register_of(core), lock_of(core)
    g = Graph(core, register, lock)
    work, head = Tree(core), (git(core, "rev-parse", "HEAD") or b"").decode().strip() or None
    for e in register:
        if only is not None and e["id"] not in only:
            continue
        snap = (snapshots or {}).get(e["id"], work)
        if e["kind"] not in READERS:
            g.unread.append({"source": e["id"], "reason": f"no reader for the kind `{e['kind']}` yet"})
            continue
        if e.get("pin") == "lock":
            pin, why = pin_of(snap, lock, e["ref"])
            ix = f"{key_of(e['ref'])}/index.jsonl"
            if pin is None or not snap.exists(ix):
                g.unread.append({"source": e["id"], "reason": why or "its index is missing"})
                continue
            if f"sha256:{sha(snap.read(ix))}" != pin.get("digest"):
                g.unread.append({"source": e["id"], "reason": "its index differs from the digest its pinned record names"})
                continue
            g.cut.append({"source": e["id"], "rev": str(pin.get("origin")), "run": str(pin.get("graph_run")), "digest": pin["digest"]})
        elif e["kind"] == "bill":                    # a bill is generated from the working files and cut where it names its revision
            b, why = (None, "a bill is generated from the CORE's working files, not from a revision (core R37)") \
                if isinstance(snap, GitTree) else bill_of(core)
            if b is None:
                g.unread.append({"source": e["id"], "reason": why})
                continue
            g.bills[e["id"]] = b
            at = {"rev": b["rev"]} if b.get("rev") and not b.get("read_at") else \
                {"read_at": b.get("read_at") or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
            g.cut.append({"source": e["id"], **at, "digest": "sha256:" + sha(yaml.safe_dump(b, sort_keys=True).encode())})
        elif not snap.exists(e["ref"]):
            g.unread.append({"source": e["id"], "reason": f"`{e['ref']}` does not exist"})
            continue
        else:
            d = digest(snap, register, e)
            if isinstance(snap, GitTree):
                g.cut.append({"source": e["id"], "rev": snap.rev, "digest": d})
            elif head and not dirty(core, register, e):
                g.cut.append({"source": e["id"], "rev": head, "digest": d})
            else:
                now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
                g.cut.append({"source": e["id"], "read_at": now, "digest": d})
        READERS[e["kind"]](snap, e, g)
    by_slug = {}
    for nid in g.nodes:
        if ":" in nid and "/" not in nid.split(":", 1)[0]:
            by_slug.setdefault(nid.split(":", 1)[1], []).append(nid)
    for x in g.edges:                                # a claim's bare `about` slug resolves to the one record of that slug
        if x["to"].startswith("*:"):
            hit = by_slug.get(x["to"][2:]) or []
            x["to"] = hit[0] if len(hit) == 1 else x["to"][2:]
    g.runs = runs_of(core)
    return g


def read_grant(other, entry, reader):
    """why the register `entry` of the commons `reader` does not read the bill of the CORE `other`, or None where it
    may (R17): its `grant` is a decision event of `other`, withdrawn by no correction, whose `grant` names the bill
    among its sources and `reader` as its recipient; availability is no permission"""
    if not entry:
        return "its register names no source of the kind `core` for it"
    if not entry.get("grant"):
        return "its register entry names no grant"
    st = grant_state(other, entry["grant"])
    if st == "held":
        scope, bill = yml(os.path.join(other, entry["grant"]))["grant"], [e["id"] for e in register_of(other) if e["kind"] == "bill"]
        st = "held" if bill and bill[0] in as_list(scope["source"]) and scope["recipient"] == reader else "outside"
    return {"held": None, "none": f"`{entry['grant']}` is no decision event of that CORE",
            "withdrawn": "a correction of that CORE has withdrawn its grant",
            "unscoped": "its grant states no structured `grant`",
            "outside": "its grant does not name that CORE's bill and this commons as recipient"}[st]


def resolve(core, at_hand=None, classes=None, seen=None):
    """a CORE's bill resolved over its levels (R26), computed and never stored: its own lines; a part of a release goes
    through its record to the bill of the CORE it was made in, and a line that reads another CORE to that CORE's bill,
    each where `at_hand` holds that CORE at that revision (`owner/repo@rev` -> folder), a read CORE only under its grant
    (R17). Visibility is decided first: a CORE whose bill the caller may not see is withheld and never named, also where
    it names no bill (R13, R27); a level not read says why, and a CORE met again on its own path is a cycle"""
    g = read(core)
    see, nodes, edges, withheld = project(g, classes)
    src = next((e["id"] for e in g.register if e["kind"] == "bill"), None)
    if src not in see and not (src is None and classes is None):
        return {"unsighted": True}
    if src is None:
        return {"core": g.core_id, "why": "its register names no source of the kind `bill` (R26)"}
    if src not in g.bills:
        return {"core": g.core_id, "why": next(u["reason"] for u in g.unread if u["source"] == src)}
    b, at_hand, seen = g.bills[src], at_hand or {}, (seen or set()) | {os.path.normpath(core)}
    cut = next(c for c in g.cut if c["source"] == src)

    def below(ref, entry=False):
        d = at_hand.get(ref)
        if not d:
            return {"why": f"`{ref}` is not at hand here"}
        if os.path.normpath(d) in seen:
            return {"cycle": ref}
        why = None if entry is False else read_grant(d, entry, g.core_id)
        return {"why": f"`{ref}` is not followed: {why} (R17)"} if why else resolve(d, at_hand, classes, seen)
    lines = []
    for x in b.get("lines") or []:
        rel, out = release_of(x), dict(x)
        if rel and rel in g.nodes:
            made = (g.nodes[rel]["content"] or {}).get("made_in")
            out["release"] = {"part": rel, "record": x["record"], "made_in": made, "below": below(str(made)) if made else {"why": "its record names no `made_in`"}}
        elif rel:
            out["release"] = {"part": rel, "why": "its record is not the one the lock pins (core R29)"}
        elif x["usage"] == "adopted":
            out["release"] = {"why": "the line names no record of its release, which is not followed (core R37)"}
        elif x["usage"] == "read" and "@" in str(x["part"]):
            out["below"] = below(str(x["part"]), next((e for e in g.register if e["kind"] == "core" and str(e.get("ref")) == str(x["part"])), None))
        lines.append(out)
    return {"core": g.core_id, "generator": b.get("generator"), **{k: v for k, v in cut.items() if k in ("rev", "read_at", "digest")}, "lines": lines}


def where_used(part, cores, at_hand=None, classes=None):
    """the permitted resolution read backwards (R27): every line that holds `part`, at the release (`<library>/<id>` or
    `@<version>`) or at one of its parts (`#<part>`), on any level the caller's resolution of `cores` reaches, each with
    the CORE asked about and the path to it, every step with the revision of its bill or the digest of its record; a
    level not read is named with its reason and a cycle with its path, so that a CORE not known is never read as one
    that does not use the part; a CORE the caller may not see is withheld, never named, and nothing is indexed"""
    out = {"part": part, "used_in": [], "unread": [], "cycles": [], "unsighted": False}

    def walk(top, level, path):
        if level.get("unsighted"):
            out["unsighted"] = True
        elif level.get("cycle"):
            out["cycles"].append({"core": top, "ref": level["cycle"], "path": path})
        elif "lines" not in level:
            out["unread"].append({"core": top or level.get("core"), **({"at": level["core"]} if top and level.get("core") else {}),
                                  "reason": level.get("why"), "path": path})
        else:
            top = top or level["core"]
            step = {"core": level["core"], **{k: level[k] for k in ("rev", "read_at") if k in level}}
            for x in level["lines"]:
                here = path + [{**step, "part": x["part"], "usage": x["usage"]}]
                if str(x["part"]) == part or str(x["part"]).startswith((part + "#", part + "@")):
                    out["used_in"].append({"core": top, "part": x["part"], "usage": x["usage"], "path": here})
                rel = x.get("release") or {}
                if rel.get("below"):
                    walk(top, rel["below"], here + [{"part": rel["part"], "record": rel["record"]}])
                elif rel.get("why"):
                    out["unread"].append({"core": top, "reason": rel["why"], "path": here})
                if x.get("below"):
                    walk(top, x["below"], here)
    for core in cores:
        walk(None, resolve(core, at_hand, classes), [])
    return out


def runs_of(core):
    """the run packages in graph/runs/: id -> (run.yml, edges, proposals)"""
    out, base = {}, os.path.join(core, "graph", "runs")
    for name in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        d = os.path.join(base, name)
        if not os.path.isfile(os.path.join(d, "run.yml")):
            continue
        ep, pp = os.path.join(d, "edges.jsonl"), os.path.join(d, "proposals.yml")
        edges = [json.loads(x) for x in open(ep, encoding="utf-8") if x.strip()] if os.path.isfile(ep) else []
        props = (yml(pp).get("proposals") or []) if os.path.isfile(pp) else []
        out[name] = (yml(os.path.join(d, "run.yml")), edges, props)
    return out


def state(run):
    """the effective state of a run: its last state"""
    s = [x.get("state") for x in run.get("states") or [] if isinstance(x, dict)]
    return s[-1] if s else None


def grant_state(core, ref, run=None, classes=None):
    """what a grant recorded at `ref` establishes for a run (graph-engine R3): `none` where no decision event of the CORE
    is there, `withdrawn` where a correction withdraws it, `unscoped` where the decision states no structured `grant`
    (prose verifies nothing), `outside` where its scope does not cover the run's restricted sources, purpose and
    recipient, and `held` only where it does; `ref` is a file directly in the CORE's own `lifecycle/events/`, reached
    by no `..`, absolute path or link out of it, and its corrections are those of that same CORE"""
    ev = os.path.realpath(os.path.join(core, "lifecycle", "events"))
    p = os.path.realpath(os.path.join(ev, os.path.basename(str(ref or ""))))
    own = ref and str(ref) == "lifecycle/events/" + os.path.basename(str(ref)) and os.path.dirname(p) == ev
    if not own or os.path.dirname(ev) != os.path.realpath(os.path.join(core, "lifecycle")):
        return "none"
    if not os.path.isfile(p) or yml(p).get("kind") != "decision":
        return "none"
    doc = yml(p)
    if any(yml(os.path.join(ev, f)).get("corrects") == doc.get("id") for f in os.listdir(ev) if f.endswith((".yml", ".yaml"))):
        return "withdrawn"
    scope = doc.get("grant")
    if not (isinstance(scope, dict) and scope.get("source") and scope.get("purpose") and scope.get("recipient")):
        return "unscoped"
    if run is not None:
        pol = run.get("policy") or {}
        restricted = {c.get("source") for c in run.get("cut") or [] if restrictions((classes or {}).get(c.get("source"), "member"))}
        if not restricted <= set(scope["source"]) or scope["purpose"] != (pol.get("grant") or {}).get("purpose")                 or scope["recipient"] != pol.get("where"):
            return "outside"
    return "held"


def grant_holds(core, ref, run=None, classes=None):
    return grant_state(core, ref, run, classes) == "held"


def sources_of(rests_on):
    return {str(r).split(":", 1)[0] for r in rests_on or []}


def project(g, classes, sources=None):
    """the graph a caller may see (R13, R24): visible nodes, visible edges, and whether anything was withheld; `sources`
    narrows the visible sources further, as an MCP grant may"""
    see = {e["id"] for e in g.register if (classes is None or e["class"] in set(classes) | {"public"})
           and (sources is None or e["id"] in sources)}
    nodes = {n: v for n, v in g.nodes.items() if v["source"] in see}
    withheld = len(see) < len(g.register)
    edges = []
    for x in g.edges:
        if x["source"] not in see or x["from"] not in nodes:
            continue
        if (x["to"] in g.nodes and x["to"] not in nodes) or (x["by"] == "computed" and not may_see(x.get("restrict", set()), classes)):
            withheld = True                          # a hidden end, or a hidden input: the edge is not there for this caller
            continue
        edges.append(x)
    for name, (run, redges, _) in g.runs.items():
        if state(run) != "released":
            continue
        pol = run.get("policy") or {}
        hosted_ok = pol.get("where") in (None, "local") or             grant_holds(g.core, (pol.get("grant") or {}).get("where"), run, {e["id"]: e["class"] for e in g.register})
        for x in redges:
            srcs = sources_of(x.get("rests_on"))
            ok = hosted_ok and all(s in g.by_id and s in see for s in srcs) and \
                may_see(restrictions(x.get("class"), *[g.cls(s) for s in srcs if s in g.by_id]), classes)
            if not ok or x.get("from") not in nodes or x.get("to") not in nodes:
                withheld = withheld or x.get("from") in g.nodes and x.get("to") in g.nodes
                continue
            edges.append({"from": x["from"], "kind": x.get("kind") or "unclassified", "to": x["to"], "by": "computed",
                          "source": "graph", "run": name, "method": x.get("method")})
    return see, nodes, edges, withheld


def partial(silences, why):
    """the sources an answer read only partly for one reason, `stale` or `unread` (R13)"""
    return [p["source"] for p in silences.get("partial") or [] if p.get("why") == why and p.get("source")]


def show(x):
    return f"{x['from']} -{x['kind']}-> {x['to']} ({x['by']}" + (f", run {x['run']}" if x.get("run") else "") + ")"


def walk(adj, start, depth, keep):
    """breadth first from a node along edges both ways, as far as `keep` allows: node -> the edges walked"""
    out, frontier, seen = {}, [(start, [])], {start}
    for _ in range(depth):
        nxt = []
        for nid, path in frontier:
            for x, other in adj.get(nid, []):
                if other in seen or not keep(x, other):
                    continue
                seen.add(other)
                out[other] = path + [x]
                nxt.append((other, path + [x]))
        frontier = nxt
    return out


def answer(core, question, k=3, classes=None, sources=None, depth=None):
    """the answer record of graph.md part 5 ($defs/answer); `depth` caps every walk, as an MCP budget may"""
    cap = (lambda d: d) if depth is None else (lambda d: min(d, depth))
    g = read(core)
    see, nodes, edges, withheld = project(g, classes, sources)
    q = words(question)
    hits = sorted(((len(q & words(n["text"])), nid) for nid, n in nodes.items()), key=lambda h: (-h[0], h[1]))
    hits = [nid for score, nid in hits if score][:k]
    adj = {}
    for x in edges:                                  # inverses are read, never stored (R6)
        adj.setdefault(x["from"], []).append((x, x["to"]))
        adj.setdefault(x["to"], []).append((x, x["from"]))
    kinds = {e["id"]: e["kind"] for e in g.register}
    patterns = {n for n, v in nodes.items() if kinds.get(v["source"]) == "patterns"}
    registry = {n for n, v in nodes.items() if kinds.get(v["source"]) == "registry"}
    reached = {}
    for start in hits:                               # the family join first (R14): record -> its stream -> family -> patterns
        if start not in registry:
            continue
        inside = walk(adj, start, cap(3), lambda x, o: x["by"] == "stated" and (o in registry or o.startswith("family:")))
        for fam in [n for n in inside if n.startswith("family:")]:
            for x, other in adj.get(fam, []):
                if other in patterns and other not in hits and other not in reached:
                    reached[other] = inside[fam] + [x]
    joined = set(reached)
    for start in hits:                               # then two steps along any visible edge; the shorter walk wins
        for other, w in walk(adj, start, cap(2), lambda x, o: o in nodes or o.startswith("family:")).items():
            if other in patterns and other not in hits and other not in joined and len(w) < len(reached.get(other, w + [0])):
                reached[other] = w
    chosen = list(reached.items())[:k]
    used = {x["run"] for _, w in chosen for x in w if x.get("run")}
    touched = set(hits) | {n for n, _ in chosen}
    not_held = sorted({x["to"] for x in edges if x["from"] in touched and x["to"] not in g.nodes and not x["to"].startswith(OUTSIDE)})
    now = {c["source"]: c["digest"] for c in g.cut}
    stale = set()
    for name in used & set(g.runs):
        for c in g.runs[name][0].get("cut") or []:
            s = c.get("source")
            if s not in g.by_id:
                stale.add(f"{s} (removed)")
            elif s in see and now.get(s) != c.get("digest"):
                stale.add(s)
    cands = [{"id": n, "file": nodes[n]["file"] or "", "via": [f"words shared with the question: {len(q & words(nodes[n]['text']))}"]} for n in hits]
    cands += [{"id": n, "file": nodes[n]["file"] or "", "via": [show(x) for x in w]} for n, w in chosen]
    return {
        "question": question,
        "cut": [c for c in g.cut if c["source"] in see],
        "runs": sorted(used),
        "method": "lexical",
        "candidates": cands,
        "silences": {"not_held": not_held, "unsighted": withheld,
                     "partial": [{"why": "stale", "source": s} for s in sorted(stale)]
                     + [{"why": "unread", "source": u["source"], "reason": u["reason"]} for u in g.unread if u["source"] in see]
                     + ([{"why": "budget", "count": len(reached) - len(chosen)}] if len(reached) > len(chosen) else [])},
    }


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("core")
    ap.add_argument("question")
    ap.add_argument("--k", type=int, default=3)
    ap.add_argument("--classes", help="the visibility classes the caller may see, comma-separated; all when omitted")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    ans = answer(a.core, a.question, a.k, a.classes.split(",") if a.classes else None)
    if a.json:
        print(json.dumps(ans, indent=2, ensure_ascii=False))
        return 0
    print(f"method {ans['method']} · runs {', '.join(ans['runs']) or 'none'}")
    for c in ans["cut"]:
        print(f"  cut  {c['source']}  {c.get('rev') or 'read at ' + c.get('read_at', '')}" + (f"  run {c['run']}" if c.get("run") else "") + f"  {c['digest'][:19]}…")
    if not ans["candidates"]:
        print("no candidate in the CORE's graph; the MCP serves the whole graph")
    for c in ans["candidates"]:
        print(f"{c['id']}  {c['file']}")
        for v in c["via"]:
            print(f"    {v}")
    s = ans["silences"]
    print(f"not held {len(s['not_held'])} · withheld {'yes' if s['unsighted'] else 'no'} · stale {', '.join(partial(s, 'stale')) or 'none'}"
          f" · left out {sum(p.get('count', 0) for p in s['partial'] if p['why'] == 'budget')} · not read {', '.join(partial(s, 'unread')) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
